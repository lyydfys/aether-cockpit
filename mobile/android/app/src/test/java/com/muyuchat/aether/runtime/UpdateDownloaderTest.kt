package com.muyuchat.aether.runtime

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.nio.file.Files

/**
 * App 内更新：资产选择 / 校验文件解析 / 下载命名 / 文案。
 *
 * 都是纯函数（不碰网络与 Android 运行时），真机上的下载与安装靠 UI 联调。
 */
class UpdateDownloaderTest {

    private fun asset(name: String, size: Long = 1_000L, url: String = "https://github.com/o/r/releases/download/v1/$name") =
        GitHubReleaseAsset(name = name, downloadUrl = url, sizeBytes = size)

    @Test
    fun prefersCurrentAbiThenUniversalThenAndroid() {
        val assets = listOf(
            asset("AetherCockpit-1.2.3-android-x86_64.apk"),
            asset("AetherCockpit-1.2.3-android-arm64-v8a.apk"),
            asset("AetherCockpit-1.2.3-android-universal.apk"),
            asset("AetherCockpit-1.2.3-windows-x64.exe"),
            asset("SHA256SUMS.txt"),
        )
        assertEquals(
            "AetherCockpit-1.2.3-android-arm64-v8a.apk",
            chooseAndroidApkAsset(assets, listOf("arm64-v8a", "armeabi-v7a"))?.name,
        )
        // 只有 v7a 的设备在没有 v7a 包时退到 universal（再退到任意 apk）。
        assertEquals(
            "AetherCockpit-1.2.3-android-universal.apk",
            chooseAndroidApkAsset(assets, listOf("armeabi-v7a"))?.name,
        )
        // 名字里只有 android、没有 ABI 的包也要能选到。
        assertEquals(
            "app-android.apk",
            chooseAndroidApkAsset(listOf(asset("app-android.apk")), listOf("arm64-v8a"))?.name,
        )
    }

    @Test
    fun returnsNullWhenNoAndroidApk() {
        val assets = listOf(
            asset("AetherCockpit-1.2.3-windows-x64.exe"),
            asset("SHA256SUMS.txt"),
            asset("source.tar.gz"),
        )
        assertNull(chooseAndroidApkAsset(assets, listOf("arm64-v8a")))
    }

    @Test
    fun findsChecksumAssetButNotTheApk() {
        val apk = asset("AetherCockpit-1.2.3-android-arm64-v8a.apk")
        assertEquals(
            "SHA256SUMS.txt",
            findSha256Asset(listOf(apk, asset("SHA256SUMS.txt")))?.name,
        )
        assertNull(findSha256Asset(listOf(apk)))
    }

    @Test
    fun parsesSha256SumsLines() {
        val text = """
            # generated by CI
            0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef  AetherCockpit-1.2.3-android-arm64-v8a.apk
            FEDCBA9876543210FEDCBA9876543210FEDCBA9876543210FEDCBA9876543210 *dist/app-windows.exe
            bad-line
        """.trimIndent()
        val sums = parseSha256Sums(text)
        assertEquals(
            "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
            sums["AetherCockpit-1.2.3-android-arm64-v8a.apk"],
        )
        // 二进制标记 `*` 与路径前缀都要剥掉，哈希统一小写。
        assertEquals(
            "fedcba9876543210fedcba9876543210fedcba9876543210fedcba9876543210",
            sums["app-windows.exe"],
        )
        assertEquals(2, sums.size)
    }

    @Test
    fun sanitizesApkFileName() {
        assertEquals("update.apk", safeApkFileName("../../evil"))
        assertEquals("a_b_c.apk", safeApkFileName("a b/c.apk"))
        assertEquals("AetherCockpit-1.2.3-android-arm64-v8a.apk", safeApkFileName("AetherCockpit-1.2.3-android-arm64-v8a.apk"))
    }

    @Test
    fun cachedApkMatchRequiresSameNameAndSize() {
        val dir = Files.createTempDirectory("aether-update-test").toFile()
        try {
            val apk = File(dir, "AetherCockpit-1.2.3-android-arm64-v8a.apk")
            apk.writeBytes(ByteArray(10))
            val asset = asset("AetherCockpit-1.2.3-android-arm64-v8a.apk", size = 10L)
            assertTrue(cachedApkMatches(apk, asset))
            // 大小对不上（下载中断/被截断）→ 必须重下。
            assertFalse(cachedApkMatches(apk, asset.copy(sizeBytes = 11L)))
            // 服务端没给大小时只看文件存在。
            assertTrue(cachedApkMatches(apk, asset.copy(sizeBytes = 0L)))
            // 名字不同（旧版本残留）→ 不复用。
            assertFalse(cachedApkMatches(apk, asset.copy(name = "AetherCockpit-9.9.9-android-arm64-v8a.apk")))
            assertFalse(cachedApkMatches(null, asset))
        } finally {
            dir.deleteRecursively()
        }
    }

    @Test
    fun installActionLabelsFollowPhase() {
        assertEquals("下载并安装", updateInstallActionLabel(UpdateInstallPhase.IDLE))
        assertEquals("下载中…", updateInstallActionLabel(UpdateInstallPhase.DOWNLOADING))
        assertEquals("安装", updateInstallActionLabel(UpdateInstallPhase.DOWNLOADED))
        assertEquals("重试下载", updateInstallActionLabel(UpdateInstallPhase.FAILED))
    }

    @Test
    fun progressTextCarriesPercentAndSizes() {
        val text = updateDownloadProgressText(12L * 1024 * 1024, 27L * 1024 * 1024)
        assertTrue(text.contains("44%"))
        assertTrue(text.contains("MB"))
        // 总大小未知时不能编一个百分比。
        val unknown = updateDownloadProgressText(2048L, -1L)
        assertTrue(unknown.contains("已下载"))
        assertFalse(unknown.contains("%"))
    }

    @Test
    fun downloadErrorsAreActionable() {
        assertEquals("已取消下载", updateDownloadErrorText("cancelled", null))
        assertTrue(updateDownloadErrorText("no_space", null).contains("空间"))
        assertTrue(updateDownloadErrorText("checksum_mismatch", null).contains("校验"))
        assertTrue(updateDownloadErrorText("http_404", null).contains("404"))
        // 未知错误码保留服务端原文，不要显示成空。
        assertEquals("磁盘只读", updateDownloadErrorText("io_error", "磁盘只读"))
    }

    @Test
    fun abiAliasesCoverCommonReleaseNames() {
        assertEquals(listOf("arm64-v8a", "arm64"), abiAliases("arm64-v8a"))
        assertEquals(listOf("armeabi-v7a", "armv7", "armeabi"), abiAliases("armeabi-v7a"))
        assertEquals(listOf("x86_64", "x86-64"), abiAliases("x86_64"))
    }
}
